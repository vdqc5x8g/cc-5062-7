"""General 2D periodic lattice geometry.

A repeat lattice is generated by two non-collinear basis vectors ``a`` and
``b`` given in *world* (actual canvas pixel) units.  Every periodic copy of a
world point ``p`` is ``p + i*a + j*b`` for integer cell identity ``(i, j)``.

Coordinate systems
------------------
world coordinates ``(x, y)``
    Actual canvas space.  Brush size/shape and rotation live here and are
    never stretched by the lattice.

cell coordinates ``(s, t)``
    ``p = s*a + t*b``.  The fundamental parallelogram is ``0 <= s,t < 1``.

index coordinates ``(u, v)``
    Pixel-grid coordinates of the stored ``W x H`` chart:
    ``s = u / W``, ``t = v / H``; pixel ``(col, row)`` center is
    ``u = col + 0.5``, ``v = row + 0.5``.

Neighbour enumeration is derived from the brush's real support region (an
ellipse metric), never from a fixed neighbour count, so a nib wider than the
cell automatically spans the required number of lattice neighbours.
"""

from __future__ import annotations

import math
from typing import Dict, List, Optional, Sequence, Tuple

from .kernel import SeamlessInputError

Vec = Tuple[float, float]
CellId = Tuple[int, int]


class Lattice:
    """Two non-collinear repeat basis vectors."""

    def __init__(self, ax: float, ay: float, bx: float, by: float,
                 *, reject_near_degenerate: bool = False,
                 min_sine: float = 1e-6):
        vals = (ax, ay, bx, by)
        if not all(math.isfinite(float(v)) for v in vals):
            raise SeamlessInputError("lattice basis values must be finite")
        self.ax = float(ax)
        self.ay = float(ay)
        self.bx = float(bx)
        self.by = float(by)

        na = math.hypot(self.ax, self.ay)
        nb = math.hypot(self.bx, self.by)
        if na <= 1e-12 or nb <= 1e-12:
            raise SeamlessInputError("lattice basis vectors must be non-zero")

        self.det = self.ax * self.by - self.ay * self.bx
        self.area = abs(self.det)
        denom = max(1.0, na * nb)
        self.relative_det = abs(self.det) / denom
        if self.det == 0.0 or self.relative_det < 1e-12:
            raise SeamlessInputError(
                "lattice basis vectors must be non-collinear "
                f"(det={self.det:g})"
            )
        if reject_near_degenerate:
            sine = self.area / (na * nb)
            if sine < min_sine:
                raise SeamlessInputError(
                    f"lattice is near-degenerate (sin angle={sine:.3g} "
                    f"< {min_sine:g})"
                )

        # Inverse matrix rows: (s,t)^T = M (x,y)^T, M = B^{-1}.
        inv = 1.0 / self.det
        self.m00 = self.by * inv
        self.m01 = -self.bx * inv
        self.m10 = -self.ay * inv
        self.m11 = self.ax * inv

    # ------------------------------------------------------------------ #
    # Constructors / introspection
    # ------------------------------------------------------------------ #
    @classmethod
    def orthogonal(cls, width: int, height: int) -> "Lattice":
        return cls(float(width), 0.0, 0.0, float(height))

    @classmethod
    def from_vectors(cls, a: Sequence[float], b: Sequence[float], **kw) -> "Lattice":
        return cls(a[0], a[1], b[0], b[1], **kw)

    @property
    def a(self) -> Vec:
        return (self.ax, self.ay)

    @property
    def b(self) -> Vec:
        return (self.bx, self.by)

    @property
    def angle_degrees(self) -> float:
        """Signed angle from a to b in degrees, in (-180, 180]."""
        cross = self.ax * self.by - self.ay * self.bx
        dot = self.ax * self.bx + self.ay * self.by
        return math.degrees(math.atan2(cross, dot))

    @property
    def is_orthogonal(self) -> bool:
        dot = self.ax * self.bx + self.ay * self.by
        return abs(dot) <= 1e-9 * max(1.0, math.hypot(self.ax, self.ay)
                                      * math.hypot(self.bx, self.by))

    def to_json(self) -> Dict[str, object]:
        return {
            "a": [self.ax, self.ay],
            "b": [self.bx, self.by],
            "det": self.det,
            "cell_area": self.area,
            "angle_deg": self.angle_degrees,
            "orthogonal": self.is_orthogonal,
        }

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"Lattice(a=({self.ax:g},{self.ay:g}), b=({self.bx:g},{self.by:g}))"

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, Lattice):
            return NotImplemented
        return (self.ax, self.ay, self.bx, self.by) == (
            other.ax, other.ay, other.bx, other.by)

    # ------------------------------------------------------------------ #
    # Coordinate transforms (fully implemented, used by kernel and server)
    # ------------------------------------------------------------------ #
    def world_to_cell(self, x: float, y: float) -> Vec:
        return (self.m00 * x + self.m01 * y,
                self.m10 * x + self.m11 * y)

    def cell_to_world(self, s: float, t: float) -> Vec:
        return (self.ax * s + self.bx * t,
                self.ay * s + self.by * t)

    def world_to_index(self, x: float, y: float,
                       width: int, height: int) -> Vec:
        s, t = self.world_to_cell(x, y)
        return (s * width, t * height)

    def index_to_world(self, u: float, v: float,
                       width: int, height: int) -> Vec:
        return self.cell_to_world(u / width, v / height)

    def fold_cell(self, s: float, t: float) -> Vec:
        """Fold cell coordinates into the half-open fundamental cell."""
        return (s - math.floor(s), t - math.floor(t))

    # ------------------------------------------------------------------ #
    # Views
    # ------------------------------------------------------------------ #
    def cell_block_bounds(self, s0: float, t0: float,
                          s1: float, t1: float) -> Tuple[float, float, float, float]:
        """Axis-aligned world bbox of a rectangle in cell coordinates."""
        xs, ys = [], []
        for s in (s0, s1):
            for t in (t0, t1):
                x, y = self.cell_to_world(s, t)
                xs.append(x)
                ys.append(y)
        return min(xs), min(ys), max(xs), max(ys)

    def fit_world_view(self, px: int = 512, margin: float = 1.35
                       ) -> Dict[str, float]:
        """Uniform-scale square world view containing the base cell.

        Returned rect has equal world width/height so one world unit maps to
        the same number of screen pixels on both axes: brush shapes are never
        distorted by the view.
        """
        x0, y0, x1, y1 = self.cell_block_bounds(0.0, 0.0, 1.0, 1.0)
        cx, cy = (x0 + x1) / 2.0, (y0 + y1) / 2.0
        half = max(x1 - x0, y1 - y0) * 0.5 * margin
        half = max(half, 1.0)
        return {
            "x0": cx - half, "y0": cy - half,
            "x1": cx + half, "y1": cy + half,
            "px": float(px), "uniform_scale": px / (2.0 * half),
        }


# --------------------------------------------------------------------------- #
# Brush metric: a rotatable ellipse in WORLD space.
# e^2 = q00*dx^2 + 2*q01*dx*dy + q11*dy^2 ; inside when e <= 1.
# --------------------------------------------------------------------------- #
def brush_metric(radius: float,
                 aspect: float = 1.0,
                 angle: float = 0.0,
                 rx: Optional[float] = None,
                 ry: Optional[float] = None,
                 metric: Optional[Sequence[float]] = None
                 ) -> Tuple[float, float, float, float, float]:
    """Return ``(q00, q01, q11, support_r, soft_default)``.

    ``angle`` is radians and rotates the local brush axes in world space.
    ``aspect = ry / rx`` when explicit ``rx/ry`` are not supplied.
    A pre-built quadratic metric ``metric=(q00,q01,q11)`` (used by basis
    deformation) takes precedence.
    """
    if radius is not None and not math.isfinite(float(radius)):
        raise SeamlessInputError("radius must be finite")
    if metric is not None:
        q00, q01, q11 = (float(metric[0]), float(metric[1]), float(metric[2]))
        if min(q00, q11) <= 0.0:
            raise SeamlessInputError("invalid brush metric")
        # Worst-case support radius from the largest semi-axis.
        tr = q00 + q11
        disc = max(0.0, (q00 - q11) ** 2 + 4.0 * q01 * q01)
        lam_min = max(1e-18, 0.5 * (tr - math.sqrt(disc)))
        support_r = 1.0 / math.sqrt(lam_min)
        return q00, q01, q11, support_r, 0.0

    r = float(radius)
    if r <= 0.0:
        raise SeamlessInputError("radius must be positive")
    if rx is not None or ry is not None:
        brx = float(rx if rx is not None else r)
        bry = float(ry if ry is not None else r * aspect)
    else:
        brx = r
        bry = r * float(aspect)
    if brx <= 0.0 or bry <= 0.0 or not math.isfinite(brx + bry):
        raise SeamlessInputError("brush radii must be positive finite")

    c, sn = math.cos(float(angle)), math.sin(float(angle))
    ix2, iy2 = 1.0 / (brx * brx), 1.0 / (bry * bry)
    q00 = c * c * ix2 + sn * sn * iy2
    q11 = sn * sn * ix2 + c * c * iy2
    q01 = c * sn * (ix2 - iy2)
    return q00, q01, q11, max(brx, bry), 0.0


def metric_extent_in_cell(q00: float, q01: float, q11: float,
                          m0: Tuple[float, float],
                          ex: Vec, ey: Vec,
                          rx: float, ry: float) -> float:
    """Exact half-extent in one cell-coordinate direction.

    For linear functional ``d_cell = m0 . d_world`` its maximum over the
    ellipse ``d^T Q d <= 1`` is
    ``sqrt(rx^2 (m0.e_x)^2 + ry^2 (m0.e_y)^2)``.
    """
    mx, my = m0
    dx_axis = mx * ex[0] + my * ex[1]
    dy_axis = mx * ey[0] + my * ey[1]
    return math.sqrt(max(0.0, rx * rx * dx_axis * dx_axis
                         + ry * ry * dy_axis * dy_axis))


def support_extents(lattice: Lattice,
                    q00: float, q01: float, q11: float
                    ) -> Tuple[float, float]:
    """Exact half-extents ``(es, et)`` of the brush support in cell coords.

    Semi-axes and principal direction are recovered from the metric's
    eigendecomposition, so this works for rotated, anisotropic and
    basis-deformed metrics alike.
    """
    tr = q00 + q11
    disc = max(0.0, (q00 - q11) ** 2 + 4.0 * q01 * q01)
    sq = math.sqrt(disc)
    lam_hi = max(1e-18, 0.5 * (tr + sq))
    lam_lo = max(1e-18, 0.5 * (tr - sq))
    r_hi_axis = 1.0 / math.sqrt(lam_hi)
    r_lo_axis = 1.0 / math.sqrt(lam_lo)
    # Principal angle of the lambda_hi eigenvector.
    if sq > 1e-18:
        phi = 0.5 * math.atan2(2.0 * q01, q00 - q11)
    else:
        phi = 0.0
    c, sn = math.cos(phi), math.sin(phi)
    e_hi = (c, sn)
    e_lo = (-sn, c)
    es = math.sqrt(
        r_hi_axis * r_hi_axis
        * (lattice.m00 * e_hi[0] + lattice.m01 * e_hi[1]) ** 2
        + r_lo_axis * r_lo_axis
        * (lattice.m00 * e_lo[0] + lattice.m01 * e_lo[1]) ** 2
    )
    et = math.sqrt(
        r_hi_axis * r_hi_axis
        * (lattice.m10 * e_hi[0] + lattice.m11 * e_hi[1]) ** 2
        + r_lo_axis * r_lo_axis
        * (lattice.m10 * e_lo[0] + lattice.m11 * e_lo[1]) ** 2
    )
    return es, et


# --------------------------------------------------------------------------- #
# Coverage-neighbour enumeration with cell-identity de-duplication.
# --------------------------------------------------------------------------- #
def cell_ranges_for_stamp(lattice: Lattice,
                          x: float, y: float,
                          es: float, et: float,
                          eps: float = 1e-9
                          ) -> Tuple[float, float, int, int, int, int]:
    """Integer lattice-index ranges of copies reaching the fundamental cell.

    Returns ``(sc, tc, i_lo, i_hi, j_lo, j_hi)`` where copy identity is
    ``(i, j)`` and its center is ``(x,y) + i*a + j*b``.  Bounds come from the
    real support extents ``es/et`` (cell units), not a fixed neighbour count.
    """
    sc, tc = lattice.world_to_cell(x, y)
    i_lo = math.ceil(-es - sc - eps)
    i_hi = math.floor(1.0 + es - sc + eps)
    j_lo = math.ceil(-et - tc - eps)
    j_hi = math.floor(1.0 + et - tc + eps)
    return sc, tc, int(i_lo), int(i_hi), int(j_lo), int(j_hi)


def enumerate_cell_ids(lattice: Lattice,
                       x: float, y: float,
                       brush: Optional[Tuple[float, float, float]] = None,
                       *,
                       radius: Optional[float] = None,
                       aspect: float = 1.0,
                       angle: float = 0.0,
                       rx: Optional[float] = None,
                       ry: Optional[float] = None,
                       metric: Optional[Sequence[float]] = None,
                       max_cells: int = 200000,
                       ) -> List[CellId]:
    """Unique lattice cell identities whose brush support meets the cell.

    Every identity appears exactly once: this is the de-duplication the
    world-grid stroke path relies on when a drag crosses a lattice vertex
    where several cells meet.
    """
    if brush is not None:
        q00, q01, q11 = brush[0], brush[1], brush[2]
        es, et = support_extents(lattice, q00, q01, q11)
    else:
        q00, q01, q11, _, _ = brush_metric(
            radius if radius is not None else 1.0,
            aspect=aspect, angle=angle, rx=rx, ry=ry, metric=metric)
        es, et = support_extents(lattice, q00, q01, q11)

    _, _, i_lo, i_hi, j_lo, j_hi = cell_ranges_for_stamp(
        lattice, x, y, es, et)

    ids: List[CellId] = []
    seen = set()
    for j in range(j_lo, j_hi + 1):
        for i in range(i_lo, i_hi + 1):
            cid = (i, j)
            if cid in seen:  # explicit identity de-duplication guard
                continue
            seen.add(cid)
            ids.append(cid)
            if len(ids) > max_cells:
                raise SeamlessInputError(
                    "brush support spans too many lattice cells "
                    f"(>{max_cells}); reduce the nib radius or enlarge the cell"
                )
    return ids


def shortest_image_shift(lattice: Lattice,
                         ds: float, dt: float,
                         search: int = 1) -> CellId:
    """Integer cell shift making a folded coordinate jump shortest in WORLD.

    For skew lattices component-wise rounding is not metric-optimal, so the
    small candidate neighbourhood is scored with the true basis metric.
    """
    best: Optional[CellId] = None
    best_len = math.inf
    for js in range(-search, search + 1):
        for jt in range(-search, search + 1):
            wx, wy = lattice.cell_to_world(ds + js, dt + jt)
            length = wx * wx + wy * wy
            if length < best_len - 1e-18:
                best_len = length
                best = (js, jt)
    return best if best is not None else (0, 0)
